package system

import (
	"context"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
	"time"

	"panel/internal/platform/linux"
)

// 安全更新识别与执行统一采用临时 APT Pinning（方案 A，见 PKG-API-011 / PKG-API-013）：
//
//  1. 动态从无参 `apt-cache policy` 提取当前系统实际启用的安全仓库 Release 元数据
//     （l=Debian-Security 或 a=/n= 以 -security 结尾），为每个安全源生成精确的
//     `Pin-Priority: 500` 规则，并叠加 Debian/Ubuntu/Ubuntu ESM 官方安全源正则兜底；
//  2. `Pin: release a=now` 保持已安装包优先级 100；
//  3. `Pin: version /.*/` 将所有其余非安全源压低到 99（< 100 禁止升级已有包到非安全版，
//     > 0 允许按需安装安全更新所依赖的新包，如内核安全更新的新 linux-image-*）；
//  4. 识别与执行均通过 `-o Dir::Etc::Preferences=<tmp> -o Dir::Etc::PreferencesParts=-`
//     在隔离视图下调用 `apt-get upgrade --with-new-pkgs`：
//     - 列表识别跑模拟 `-s`，解析 `Inst <pkg>` 集合作为权威安全更新判定；
//     - 安全升级直接跑 `upgrade --with-new-pkgs -y`，不修改 `/etc/apt/`，不污染
//       `Auto-Installed` 标记，同时解决 Ubuntu `-updates` 覆盖 `-security` 与
//       Debian `label=Debian-Security` 缺失的问题。

const (
	// aptPolicyGlobalTimeout 限制无参 apt-cache policy 探测安全仓库的耗时。
	aptPolicyGlobalTimeout = 10 * time.Second
	// aptSecuritySimulateTimeout 限制 apt-get -s 模拟安全升级的耗时。
	aptSecuritySimulateTimeout = 30 * time.Second
)

var aptPinSafeTokenPattern = regexp.MustCompile(`^[A-Za-z0-9._+-]+$`)

// aptRelease 表示 apt-cache policy 的一条 release 元数据（o=, a=, n=, l=）。
type aptRelease struct {
	Origin   string
	Archive  string
	Codename string
	Label    string
}

// applyAptSecurity 使用临时安全 APT Pinning 模拟 `apt-get upgrade --with-new-pkgs`，
// 为可升级列表补充权威安全判定。它是纯尽力而为的步骤：任何失败都只让包保持
// SecurityKnown=false，绝不影响 PackageUpdates 本身。
func applyAptSecurity(ctx context.Context, updates []linux.PackageUpdate) {
	if len(updates) == 0 {
		return
	}
	prefPath, cleanup, err := writeSecurityPreferencesFile(ctx)
	if err != nil {
		return
	}
	defer cleanup()

	inst, err := simulateSecurityUpgrade(ctx, prefPath)
	if err != nil {
		return
	}
	for i := range updates {
		name := strings.TrimSpace(updates[i].Name)
		if name == "" {
			continue
		}
		_, isSec := inst[name]
		if !isSec {
			if base, _, ok := strings.Cut(name, ":"); ok {
				_, isSec = inst[base]
			}
		}
		updates[i].Security = isSec
		updates[i].SecurityKnown = true
	}
}

// simulateSecurityUpgrade 在临时安全 Pin 视图下执行 `apt-get -s upgrade --with-new-pkgs`，
// 返回 APT 计划安装或升级的包名集合。
func simulateSecurityUpgrade(ctx context.Context, prefPath string) (map[string]struct{}, error) {
	args := securityAptPreferencesArgs(prefPath)
	args = append(args, "-s", "upgrade", "--with-new-pkgs")
	out, err := runCommand(ctx, aptSecuritySimulateTimeout, "apt-get", args...)
	if err != nil {
		return nil, err
	}
	return parseAptSimulateInst(out), nil
}

// securityAptPreferencesArgs 返回隔离加载临时安全 Pin 文件的 apt-get 参数。
func securityAptPreferencesArgs(prefPath string) []string {
	return []string{
		"-o", "Dir::Etc::Preferences=" + prefPath,
		"-o", "Dir::Etc::PreferencesParts=-",
	}
}

// writeSecurityPreferencesFile 创建仅本次调用生效的临时 APT preferences 文件。
// 调用方必须通过返回的 cleanup 函数删除临时文件。
func writeSecurityPreferencesFile(ctx context.Context) (string, func(), error) {
	content := buildSecurityPreferences(ctx)
	file, err := os.CreateTemp("", "panel-apt-security-*.pref")
	if err != nil {
		return "", nil, err
	}
	path := file.Name()
	cleanup := func() { _ = os.Remove(path) }
	if err := file.Chmod(0o600); err != nil {
		_ = file.Close()
		cleanup()
		return "", nil, err
	}
	if _, err := file.WriteString(content); err != nil {
		_ = file.Close()
		cleanup()
		return "", nil, err
	}
	if err := file.Close(); err != nil {
		cleanup()
		return "", nil, err
	}
	return path, cleanup, nil
}

// buildSecurityPreferences 生成安全专用 APT Pin 规则。
// APT 对 general-form (`Package: *`) 采用 first-match-wins：
//  1. 精确匹配本机已启用的安全源 + 官方安全源正则兜底（Pin-Priority: 500）；
//  2. 保留已安装包（Pin: release a=now，Pin-Priority: 100）；
//  3. 其余所有非安全源压低到 99（不升级已有包，但允许按需安装未安装的新依赖）。
func buildSecurityPreferences(ctx context.Context) string {
	var dynamicReleases []aptRelease
	if out, err := runCommand(ctx, aptPolicyGlobalTimeout, "apt-cache", "policy"); err == nil {
		dynamicReleases = parseGlobalAptPolicySecurityReleases(out)
	}
	return renderSecurityPreferences(dynamicReleases)
}

func renderSecurityPreferences(dynamicReleases []aptRelease) string {
	var b strings.Builder
	b.WriteString("# Generated by panel-agent for security-only APT operations.\n\n")

	seenExpr := map[string]struct{}{}
	writePin := func(expr string, priority int) {
		if expr == "" {
			return
		}
		if _, exists := seenExpr[expr]; exists {
			return
		}
		seenExpr[expr] = struct{}{}
		fmt.Fprintf(&b, "Package: *\nPin: %s\nPin-Priority: %d\n\n", expr, priority)
	}

	// 1. 本机实际启用的安全仓库精确匹配（兼容自定义/国内镜像站与各类安全归档命名）。
	for _, rel := range dynamicReleases {
		if expr := formatReleasePinExpr(rel); expr != "" {
			writePin(expr, 500)
		}
	}

	// 2. 官方安全源正则兜底（防止无参 apt-cache policy 偶发失败或部分字段缺省）。
	fallbackSecurityPins := []string{
		"release o=Debian,l=Debian-Security",
		"release o=Debian,a=/.*-security$/",
		"release o=Debian,n=/.*-security$/",
		"release o=Ubuntu,a=/.*-security$/",
		"release o=Ubuntu,n=/.*-security$/",
		"release o=/^UbuntuESM/,a=/.*-security$/",
	}
	for _, expr := range fallbackSecurityPins {
		writePin(expr, 500)
	}

	// 3. 保持已安装包优先级 100，随后将所有其余非安全源压低到 99。
	writePin("release a=now", 100)
	writePin("version /.*/", 99)
	return b.String()
}

// formatReleasePinExpr 把解析出的安全源 Release 元数据格式化为 `release o=...,a=...,n=...,l=...`。
func formatReleasePinExpr(rel aptRelease) string {
	var parts []string
	appendPart := func(key, value string) {
		value = strings.TrimSpace(value)
		if value != "" && aptPinSafeTokenPattern.MatchString(value) {
			parts = append(parts, key+"="+value)
		}
	}
	appendPart("o", rel.Origin)
	appendPart("a", rel.Archive)
	appendPart("n", rel.Codename)
	appendPart("l", rel.Label)
	if len(parts) == 0 {
		return ""
	}
	return "release " + strings.Join(parts, ",")
}

// parseGlobalAptPolicySecurityReleases 解析无参 `apt-cache policy` 输出，
// 提取所有安全仓库的 release 元数据并按稳定顺序去重返回。
func parseGlobalAptPolicySecurityReleases(output string) []aptRelease {
	lines := strings.Split(strings.ReplaceAll(output, "\r\n", "\n"), "\n")
	seen := map[string]struct{}{}
	var releases []aptRelease
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(strings.ToLower(trimmed), "release ") {
			continue
		}
		rel := parseAptReleaseLine(strings.TrimSpace(trimmed[len("release "):]))
		if !isSecurityRelease(rel) {
			continue
		}
		key := strings.ToLower(strings.Join([]string{rel.Origin, rel.Archive, rel.Codename, rel.Label}, "\x00"))
		if _, ok := seen[key]; ok {
			continue
		}
		seen[key] = struct{}{}
		releases = append(releases, rel)
	}
	sort.Slice(releases, func(i, j int) bool {
		return formatReleasePinExpr(releases[i]) < formatReleasePinExpr(releases[j])
	})
	return releases
}

// isSecurityRelease 判定一条 APT Release 元数据是否代表安全更新仓库。
func isSecurityRelease(rel aptRelease) bool {
	if strings.EqualFold(strings.TrimSpace(rel.Label), "Debian-Security") {
		return true
	}
	for _, field := range []string{rel.Archive, rel.Codename} {
		if strings.HasSuffix(strings.ToLower(strings.TrimSpace(field)), "-security") {
			return true
		}
	}
	return false
}

// parseAptReleaseLine 解析 `o=Debian,a=stable-security,n=bookworm-security,l=Debian-Security,...`。
func parseAptReleaseLine(value string) aptRelease {
	var release aptRelease
	for _, field := range strings.Split(value, ",") {
		key, val, ok := strings.Cut(field, "=")
		if !ok {
			continue
		}
		val = strings.TrimSpace(val)
		switch strings.ToLower(strings.TrimSpace(key)) {
		case "o", "origin":
			release.Origin = val
		case "a", "archive":
			release.Archive = val
		case "n", "codename":
			release.Codename = val
		case "l", "label":
			release.Label = val
		}
	}
	return release
}

// parseAptSimulateInst 解析 `apt-get -s` 输出中的 `Inst <pkg> ...` 行，
// 返回计划升级或新安装的包名集合（含去除 `:arch` 后缀的基础包名）。
func parseAptSimulateInst(output string) map[string]struct{} {
	pkgs := map[string]struct{}{}
	for _, line := range strings.Split(strings.ReplaceAll(output, "\r\n", "\n"), "\n") {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "Inst ") {
			continue
		}
		fields := strings.Fields(trimmed)
		if len(fields) < 2 {
			continue
		}
		name := strings.TrimSpace(fields[1])
		if name == "" {
			continue
		}
		pkgs[name] = struct{}{}
		if base, _, ok := strings.Cut(name, ":"); ok && base != "" {
			pkgs[base] = struct{}{}
		}
	}
	return pkgs
}
