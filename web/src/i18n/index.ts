const state = reactive({ locale: (globalThis.localStorage?.getItem('panel.locale') as Locale) || 'zh-CN' });

export function useI18n() {
  const locale = computed(() => state.locale);

  function setLocale(next: Locale) {
    state.locale = next;
    globalThis.localStorage?.setItem('panel.locale', next);
  }

  function t(key: string, params?: Record<string, string | number>) {
    let text = messages[state.locale][key] || messages.en[key] || key;
    if (params) {
      Object.entries(params).forEach(([name, value]) => {
        text = text.split(`{${name}}`).join(String(value));
      });
    }
    return text;
  }

  return { locale, setLocale, t };
}

export function translateRuntimeEventType(t: (key: string, params?: Record<string, string | number>) => string, value: string) {
  const key = `runtimeEventTypes.${value}`;
  const label = t(key);
  return label === key ? value : label;
}
