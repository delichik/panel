type MessageTree = typeof messages.en;

const locale = ref<SupportedLocale>(readStoredLocale());

function readStoredLocale(): SupportedLocale {
  return normalizeLocale(globalThis.localStorage?.getItem?.(STORAGE_KEY));
}

export function normalizeLocale(value: unknown): SupportedLocale {
  const candidate = String(value ?? "")
    .trim()
    .toLowerCase();
  if (
    candidate === "zh" ||
    candidate === "zh-cn" ||
    candidate === "zh-hans" ||
    candidate === "cn"
  ) {
    return "zh-CN";
  }
  return "en";
}

export function getLocale() {
  return locale.value;
}

export function getLocaleHeader() {
  return locale.value;
}

export function setLocale(value: unknown) {
  const next = normalizeLocale(value);
  locale.value = next;
  globalThis.localStorage?.setItem?.(STORAGE_KEY, next);
  syncDocumentLanguage(next);
}

export function syncDocumentLanguage(value: SupportedLocale = locale.value) {
  if (typeof document !== "undefined") {
    document.documentElement.lang = value;
  }
}

function lookup(
  path: string,
  source: MessageTree | (typeof messages)["zh-CN"],
): string | undefined {
  let current: unknown = source;
  for (const segment of path.split(".")) {
    if (!current || typeof current !== "object" || !(segment in current)) {
      return undefined;
    }
    current = (current as Record<string, unknown>)[segment];
  }
  return typeof current === "string" ? current : undefined;
}

export function t(
  key: string,
  params?: Record<string, string | number | null | undefined>,
) {
  const active = messages[locale.value];
  const template = lookup(key, active) ?? lookup(key, messages.en) ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    String(params[name] ?? ""),
  );
}

